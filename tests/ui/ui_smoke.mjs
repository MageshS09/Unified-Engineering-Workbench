// End-to-end UI test: starts Launch.exe (--no-browser) and a headless Edge/Chrome, drives the real page
// through the Chrome DevTools Protocol (clicks, typing, file inputs and real mouse drag/wheel/click events),
// asserts on what a user would see, and writes screenshots plus a timestamped walkthrough
// (<screenshot-dir>/walkthrough.md) that includes the application log.
// Optional test: needs Node >= 22 and Edge or Chrome (set BROWSER_PATH to override).
//
//   node tests/ui/ui_smoke.mjs <path-to-Launch.exe> [screenshot-dir]
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
const launchExe = path.resolve(process.argv[2] || path.join(repo, 'build', 'Launch.exe'));
const shotDir = path.resolve(process.argv[3] || path.join(repo, 'docs', 'screenshots'));
const badSamples = path.join(repo, 'tests', 'data');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const stamp = () => new Date().toISOString();

function findBrowser() {
  const candidates = [process.env.BROWSER_PATH,
    path.join(process.env['ProgramFiles(x86)'] || '', 'Microsoft', 'Edge', 'Application', 'msedge.exe'),
    path.join(process.env.ProgramFiles || '', 'Microsoft', 'Edge', 'Application', 'msedge.exe'),
    path.join(process.env.ProgramFiles || '', 'Google', 'Chrome', 'Application', 'chrome.exe')];
  const found = candidates.find((c) => c && fs.existsSync(c));
  if (!found) throw new Error('No Edge/Chrome found. Set BROWSER_PATH.');
  return found;
}

let failures = 0;
let passes = 0;
const consoleErrors = [];
const timeline = [];  // chronological checks and screenshots, rendered into walkthrough.md

function check(name, ok, detail = '') {
  timeline.push({ kind: 'check', time: stamp(), name, ok, detail });
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${ok || !detail ? '' : `  -> ${detail}`}`);
  if (ok) passes++; else failures++;
}

function writeWalkthrough(appLog, browserName) {
  const lines = ['# UI walkthrough (automated, timestamped)', '',
    `Generated by \`tests/ui/ui_smoke.mjs\` on ${stamp()} by driving the real page in headless ${browserName} against \`Launch.exe\`.`,
    `Result: **${passes} checks passed, ${failures} failed.** Times are UTC. Mouse rotate (drag), zoom (wheel), pan (right-drag) and hover are real input events sent through the DevTools protocol. The node *click* is the one exception: Plotly's 3D click detection does not fire from synthetic input, so the test emits the same \`plotly_click\` event and checks the page's handler.`, ''];
  for (const e of timeline) {
    if (e.kind === 'shot') lines.push('', `### ${e.caption}`, `\`${e.time}\``, '', `![${e.caption}](${e.file})`, '');
    else lines.push(`- \`${e.time.slice(11, 23)}\` ${e.ok ? 'PASS' : '**FAIL**'}: ${e.name}${e.ok || !e.detail ? '' : ` (${e.detail.slice(0, 200)})`}`);
  }
  lines.push('', '## Application log (`logs/workbench.log`)', '', '```', appLog.trim(), '```', '');
  fs.writeFileSync(path.join(shotDir, 'walkthrough.md'), lines.join('\n'));
}

async function main() {
  fs.mkdirSync(shotDir, { recursive: true });
  const logFile = path.join(path.dirname(launchExe), 'logs', 'workbench.log');
  fs.rmSync(logFile, { force: true });
  const app = spawn(launchExe, ['--no-browser'], { stdio: 'ignore' });
  let appExited = false;
  app.on('exit', () => { appExited = true; });
  let port = 0;
  for (let i = 0; i < 100 && !port; i++) {
    await sleep(100);
    if (fs.existsSync(logFile)) port = Number((/127\.0\.0\.1:(\d+)/.exec(fs.readFileSync(logFile, 'utf8')) || [])[1]) || 0;
  }
  if (!port) throw new Error('Launch.exe did not report a port in logs/workbench.log');

  const browserExe = findBrowser();
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'wb-ui-'));
  const debugPort = 9300 + Math.floor(Math.random() * 500);
  const browser = spawn(browserExe, ['--headless=new', `--remote-debugging-port=${debugPort}`, `--user-data-dir=${profile}`,
    '--window-size=1280,900', '--no-first-run', '--enable-unsafe-swiftshader', '--use-angle=swiftshader', '--ignore-gpu-blocklist',
    'about:blank'], { stdio: 'ignore' });

  try {
    let target;
    for (let i = 0; i < 100 && !target; i++) {
      await sleep(100);
      try { target = (await (await fetch(`http://127.0.0.1:${debugPort}/json/list`)).json()).find((t) => t.type === 'page'); } catch { /* not up yet */ }
    }
    if (!target) throw new Error('Browser did not expose a DevTools page');
    const ws = new WebSocket(target.webSocketDebuggerUrl);
    await new Promise((r) => (ws.onopen = r));
    let nextId = 1;
    const pending = new Map();
    ws.onmessage = (ev) => {
      const m = JSON.parse(ev.data);
      if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); return; }
      if (m.method === 'Runtime.exceptionThrown') consoleErrors.push(m.params.exceptionDetails.exception?.description || m.params.exceptionDetails.text);
      if (m.method === 'Runtime.consoleAPICalled' && m.params.type === 'error') consoleErrors.push(m.params.args.map((a) => a.value ?? a.description).join(' '));
    };
    const cdp = (method, params = {}) => new Promise((res, rej) => {
      const id = nextId++;
      pending.set(id, (m) => (m.error ? rej(new Error(`${method}: ${m.error.message}`)) : res(m.result)));
      ws.send(JSON.stringify({ id, method, params }));
    });
    const evalJs = async (expr) => {
      const r = await cdp('Runtime.evaluate', { expression: expr, returnByValue: true, awaitPromise: true });
      if (r.exceptionDetails) throw new Error(`eval failed: ${expr}\n${r.exceptionDetails.exception?.description}`);
      return r.result.value;
    };
    const text = (id) => evalJs(`document.getElementById(${JSON.stringify(id)}).textContent`);
    const click = (id) => evalJs(`document.getElementById(${JSON.stringify(id)}).click()`);
    const waitFor = async (what, expr, timeoutMs = 15000) => {
      const end = Date.now() + timeoutMs;
      while (Date.now() < end) {
        if (await evalJs(expr).catch(() => false)) return true;
        await sleep(100);
      }
      check(`wait: ${what}`, false, 'timed out');
      return false;
    };
    const showTab = (tab) => evalJs(`document.querySelector('#tabs button[data-tab=${tab}]').click()`);
    let shotNo = 0;
    // viewportOnly: capture what is on screen without resizing (resizing makes the pointer leave, which hides hover labels).
    const shot = async (name, caption, viewportOnly = false) => {
      let r;
      if (viewportOnly) {
        r = await cdp('Page.captureScreenshot', { format: 'png' });
      } else {
        // Resize the viewport to the page height so the fixed status bar sits at the bottom of the image.
        const { contentSize } = await cdp('Page.getLayoutMetrics');
        const height = Math.min(Math.ceil(contentSize.height), 3200);
        await cdp('Emulation.setDeviceMetricsOverride', { width: 1280, height, deviceScaleFactor: 1, mobile: false });
        await sleep(400);  // let Plotly re-layout
        r = await cdp('Page.captureScreenshot', { format: 'png' });
        await cdp('Emulation.setDeviceMetricsOverride', { width: 1280, height: 900, deviceScaleFactor: 1, mobile: false });
      }
      const file = `${String(++shotNo).padStart(2, '0')}_${name}.png`;
      fs.writeFileSync(path.join(shotDir, file), Buffer.from(r.data, 'base64'));
      timeline.push({ kind: 'shot', time: stamp(), file, caption: caption || name });
    };

    // ---- real mouse input ----
    const mouse = (type, x, y, extra = {}) => cdp('Input.dispatchMouseEvent', { type, x, y, button: 'none', buttons: 0, clickCount: 0, ...extra });
    const drag = async (x1, y1, x2, y2, button = 'left') => {
      const buttons = button === 'left' ? 1 : 2;
      await mouse('mouseMoved', x1, y1);
      await mouse('mousePressed', x1, y1, { button, buttons, clickCount: 1 });
      for (let i = 1; i <= 10; i++) { await mouse('mouseMoved', x1 + ((x2 - x1) * i) / 10, y1 + ((y2 - y1) * i) / 10, { button, buttons }); await sleep(20); }
      await mouse('mouseReleased', x2, y2, { button, buttons: 0, clickCount: 1 });
      await sleep(300);
    };
    const plotRect = (id) => evalJs(`(() => { const e = document.getElementById('${id}'); e.scrollIntoView({ block: 'center' }); const r = e.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height }; })()`);
    const camera = (id) => evalJs(`(() => { const s = document.getElementById('${id}')._fullLayout.scene._scene; const c = s.getCamera(); return { eye: c.eye, center: c.center }; })()`);
    const dist = (c) => Math.hypot(c.eye.x - c.center.x, c.eye.y - c.center.y, c.eye.z - c.center.z);
    const moved = (a, b) => Math.hypot(a.eye.x - b.eye.x, a.eye.y - b.eye.y, a.eye.z - b.eye.z) > 1e-3;

    await cdp('Page.enable'); await cdp('Runtime.enable'); await cdp('DOM.enable');
    await cdp('Emulation.setDeviceMetricsOverride', { width: 1280, height: 900, deviceScaleFactor: 1, mobile: false });
    await cdp('Page.navigate', { url: `http://127.0.0.1:${port}/` });
    await waitFor('backend ready', `document.getElementById('status-text').textContent.includes('Backend ready')`);
    check('status bar shows "Backend ready"', (await text('status-text')).includes('Backend ready'));
    check('four tabs present', (await evalJs(`[...document.querySelectorAll('#tabs button')].map(b => b.textContent).join('|')`)) === 'Geometry|Thermal Analysis|Performance|Hardware');
    await shot('start', 'Start page: Geometry tab, status bar "Backend ready"');

    // ---- Geometry: STL ----
    await click('stl-sample');
    await waitFor('STL stats', `document.getElementById('stl-stats').textContent.includes('Triangles')`);
    const stl = (await text('stl-stats')).replace(/\s/g, '');
    check('STL sample: 12 triangles, 8 vertices', /Triangles12/.test(stl) && /Uniquevertices8/.test(stl), stl);
    check('STL mesh3d trace drawn', await evalJs(`document.getElementById('stl-plot').data?.[0]?.type === 'mesh3d'`));
    check('Fit to view enabled after load', await evalJs(`!document.getElementById('stl-fit').disabled`));
    await sleep(600);
    await shot('stl_loaded', 'STL sample loaded: 12 triangles, statistics, 3D view');

    const centreOf = async (id) => { const r = await plotRect(id); return { cx: r.x + r.w / 2, cy: r.y + r.h / 2 }; };
    let { cx, cy } = await centreOf('stl-plot');
    const cam0 = await camera('stl-plot');
    await drag(cx - 80, cy, cx + 120, cy + 60, 'left');
    const cam1 = await camera('stl-plot');
    check('mouse drag rotates the STL model (camera eye changed)', moved(cam0, cam1), JSON.stringify([cam0.eye, cam1.eye]));
    await shot('stl_rotated', 'After a real mouse drag: model rotated');
    ({ cx, cy } = await centreOf('stl-plot'));  // the screenshot changed the scroll position
    await mouse('mouseMoved', cx, cy);  // the pointer must be over the 3D canvas before it accepts wheel events
    await sleep(100);
    await mouse('mouseWheel', cx, cy, { deltaX: 0, deltaY: -150 });
    await sleep(600);
    const cam2 = await camera('stl-plot');
    check('mouse wheel zooms (camera distance changed)', Math.abs(dist(cam2) - dist(cam1)) > 1e-3, `${dist(cam1).toFixed(3)} -> ${dist(cam2).toFixed(3)}`);
    await mouse('mouseMoved', cx, cy);
    await sleep(100);
    await drag(cx, cy, cx + 100, cy + 40, 'right');
    const cam3 = await camera('stl-plot');
    const centerMoved = Math.hypot(cam3.center.x - cam2.center.x, cam3.center.y - cam2.center.y, cam3.center.z - cam2.center.z) > 1e-3;
    check('right-button drag pans (camera centre changed)', centerMoved || moved(cam2, cam3), JSON.stringify([cam2.center, cam3.center]));
    await shot('stl_zoom_pan', 'After wheel zoom and right-drag pan');
    ({ cx, cy } = await centreOf('stl-plot'));
    await click('stl-fit');
    await sleep(700);
    const cam4 = await camera('stl-plot');
    check('Fit to view restores the default camera', Math.abs(cam4.eye.x - 1.25) < 0.05 && Math.abs(cam4.eye.y - 1.25) < 0.05 && Math.abs(cam4.eye.z - 1.25) < 0.05 && Math.abs(cam4.center.x) < 0.05, JSON.stringify(cam4));
    await shot('stl_fit', 'After "Fit to view": default camera restored');

    // ---- Geometry: CSV point cloud ----
    await click('csv-sample');
    await waitFor('CSV stats', `document.getElementById('csv-stats').textContent.includes('Nodes')`);
    check('CSV sample: 1331 nodes', (await text('csv-stats')).includes('1331'));
    check('point cloud is scatter3d with colourbar "Temperature (°C)"',
      await evalJs(`(() => { const t = document.getElementById('csv-plot').data?.[0]; return t?.type === 'scatter3d' && JSON.stringify(t.marker.colorbar.title).includes('Temperature (°C)'); })()`));
    check('hover template shows node_id, x, y, z and T', await evalJs(`(() => { const h = document.getElementById('csv-plot').data[0].hovertemplate; return ['node_id','x ','y ','z ','T '].every(s => h.includes(s)); })()`));
    await evalJs(`document.getElementById('node-id').value = '1'`);
    await click('node-lookup');
    await waitFor('node info', `document.getElementById('node-info').textContent.includes('Node 1')`);
    check('node lookup returns node 1', (await text('node-info')).includes('T = 20.0937'));
    await sleep(600);

    // hover and click a real point with the mouse
    const r2 = await plotRect('csv-plot');
    // 3D picking needs a few animation frames per position, so wait ~90 ms after each move.
    let hit = null;
    for (let y = r2.y + r2.h * 0.3; y < r2.y + r2.h * 0.85 && !hit; y += 14) {
      for (let x = r2.x + r2.w * 0.3; x < r2.x + r2.w * 0.6 && !hit; x += 14) {
        await mouse('mouseMoved', x, y);
        await sleep(90);
        if (await evalJs(`!!document.querySelector('#csv-plot .hovertext')`)) hit = { x, y };
      }
    }
    check('hovering a node with the mouse shows a label', !!hit);
    if (hit) {
      const label = await evalJs(`document.querySelector('#csv-plot .hovertext').textContent`);
      check('hover label shows node_id, x, y, z and T', /node_id/.test(label) && /°C/.test(label), label);
      await shot('csv_hover', 'Point cloud: hover label (node_id, x, y, z, T) shown by a real mouse hover', true);
      // Plotly's 3D click detection polls the button state per animation frame and does not fire from
      // synthetic DevTools input (hover does), so emit the event Plotly would send and test the app's handler.
      await evalJs(`(() => { const gd = document.getElementById('csv-plot'); const d = gd.data[0]; const n = 100;
        gd.emit('plotly_click', { points: [{ pointNumber: n, customdata: d.customdata[n], x: d.x[n], y: d.y[n], z: d.z[n] }] }); })()`);
      await waitFor('selected node', `document.getElementById('node-info').textContent.startsWith('Selected node')`, 5000);
      check('click handler shows the selected node details (event emitted programmatically)',
        /Selected node \d+: x = .* m, y = .* m, z = .* m, T = [\d.]+ °C/.test(await text('node-info')), await text('node-info'));
    }
    await shot('csv_loaded', 'ANSYS-style CSV (synthetic): coloured point cloud, legend, node inspector');

    // negative uploads through the real file inputs
    const doc = await cdp('DOM.getDocument');
    const input = await cdp('DOM.querySelector', { nodeId: doc.root.nodeId, selector: '#stl-file' });
    await cdp('DOM.setFileInputFiles', { nodeId: input.nodeId, files: [path.join(badSamples, 'binary.stl')] });
    await waitFor('binary STL error', `document.getElementById('stl-msg').textContent.length > 0`);
    check('binary STL is rejected with an actionable message', (await text('stl-msg')).includes('binary STL') && (await text('stl-msg')).includes('re-export'), await text('stl-msg'));
    const input2 = await cdp('DOM.querySelector', { nodeId: doc.root.nodeId, selector: '#csv-file' });
    await cdp('DOM.setFileInputFiles', { nodeId: input2.nodeId, files: [path.join(badSamples, 'duplicate_id.csv')] });
    await waitFor('duplicate id error', `document.getElementById('csv-msg').textContent.includes('duplicate')`);
    check('CSV with duplicate node_id is rejected with its line number', (await text('csv-msg')).includes('line 4'), await text('csv-msg'));
    await evalJs(`document.getElementById('stl-msg').scrollIntoView({ block: 'center' })`);
    await shot('rejected_files', 'Malformed files rejected with line numbers and advice (binary STL, duplicate node_id)');

    // ---- Thermal ----
    await showTab('thermal');
    await evalJs(`document.querySelector('#fea-form [name=k_W_mK]').value = '-1'`);
    await click('fea-solve');
    check('invalid k is explained before any request', (await text('fea-msg')).includes('Conductivity k') && (await text('fea-msg')).includes('greater than 0'), await text('fea-msg'));
    await shot('thermal_validation', 'Thermal tab: invalid conductivity explained, input highlighted');
    await evalJs(`document.querySelector('#fea-form [name=k_W_mK]').value = '10'`);
    await click('fea-solve');
    await waitFor('FEA table', `document.querySelectorAll('#fea-table tr').length === 5`);
    const feaTable = (await text('fea-table')).replace(/\s/g, '');
    check('convergence table: midpoint errors 1.25, 0.3125, 0.078125, 0.01953125',
      ['1.2500000', '0.31250000', '0.078125000', '0.019531250'].every((v) => feaTable.includes(v)), feaTable);
    check('observed order 2.000', (feaTable.match(/2\.000/g) || []).length >= 3);
    check('three FEA plots drawn', await evalJs(`['fea-plot','fea-err-plot','fea-conv-plot'].every(id => document.getElementById(id).data?.length > 0)`));
    check('temperature plot has FE N=10..80 and exact', await evalJs(`document.getElementById('fea-plot').data.length === 5`));
    check('export buttons enabled', await evalJs(`['fea-export-conv','fea-export-json','fea-export-sol'].every(id => !document.getElementById(id).disabled)`));
    await click('bp-run');
    await waitFor('backprop table', `document.querySelectorAll('#bp-table tr').length === 5`);
    const bp = await text('bp-table');
    check('backprop: 4 gradients pass the finite-difference check', (bp.match(/yes/g) || []).length === 4, bp);
    check('backprop: dJ/dw = -1.2094645', bp.includes('-1.2094645'));
    await sleep(800);
    await shot('thermal_solved', 'Thermal tab solved: FE vs exact, midpoint error, convergence, backprop panel');

    // ---- Performance ----
    await showTab('performance');
    await click('perf-run');
    await waitFor('perf table', `document.querySelectorAll('#perf-table tr').length >= 4`, 30000);
    const perf = await text('perf-table');
    check('performance table lists serial and parallel rows', perf.includes('serial') && perf.includes('parallel'), perf);
    check('serial/parallel agreement reported as PASS', (await text('perf-msg')).includes('PASS'), await text('perf-msg'));
    check('speedup plot drawn', await evalJs(`document.getElementById('perf-plot').data?.length === 2`));
    await sleep(500);
    await shot('performance', 'Performance tab: serial vs parallel table and speedup plot');

    await evalJs(`(() => { const f = document.getElementById('perf-form'); f.elements.cases.value = '3000'; f.elements.mesh.value = '20000'; })()`);
    await click('perf-run');
    await waitFor('job running', `document.getElementById('status-text').textContent.includes('%')`);
    check('run buttons are disabled while a job runs', await evalJs(`document.getElementById('perf-run').disabled && document.getElementById('fea-solve').disabled`));
    check('Cancel button is visible during the job', await evalJs(`!document.getElementById('status-cancel').hidden`));
    await shot('job_running', 'A long job running: progress in the status bar, Cancel visible, run buttons disabled');
    await click('status-cancel');
    await waitFor('cancelled', `document.getElementById('status-text').textContent.includes('cancelled')`, 30000);
    check('cancelled run keeps no results and says so', (await text('perf-msg')).includes('no partial results'), await text('perf-msg'));
    check('buttons re-enabled after cancel', await evalJs(`!document.getElementById('perf-run').disabled && !document.getElementById('fea-solve').disabled`));
    await shot('job_cancelled', 'After Cancel: "cancelled, no results were kept"');
    await evalJs(`(() => { const f = document.getElementById('perf-form'); f.elements.cases.value = '400'; f.elements.mesh.value = '2000'; })()`);

    // ---- Hardware ----
    await showTab('hardware');
    await waitFor('device table', `document.querySelectorAll('#hw-table tr').length === 4`);
    check('3 devices listed, all badged SIMULATED', (await evalJs(`document.querySelectorAll('#hw-table .badge').length`)) === 3);
    await click('hw-fault');
    await waitFor('fault on', `document.getElementById('hw-log').textContent.includes('fault injection ON')`);
    await evalJs(`document.querySelector('#hw-table button[data-hw=retry][data-id=jtag0]').click()`);
    await waitFor('retry result', `document.getElementById('hw-log').textContent.includes('attempt 3 OK')`);
    const log = await text('hw-log');
    check('timeout fault shown, then recovery by retry with backoff', log.includes('attempt 1 FAILED') && log.includes('attempt 2 FAILED') && log.includes('attempt 3 OK') && log.includes('SIMULATED timeout'), log);
    await evalJs(`document.querySelector('#hw-table button[data-hw=telemetry][data-id=jtag0]').click()`);
    await waitFor('telemetry', `document.getElementById('hw-telemetry').textContent.includes('SIMULATED')`);
    check('telemetry message is labelled SIMULATED', (await text('hw-telemetry')).includes('"label": "SIMULATED"'));
    await evalJs(`document.querySelector('#hw-table button[data-hw=caps][data-id=jtag0]').click()`);
    await waitFor('caps', `document.getElementById('hw-caps').textContent.includes('compute')`);
    check('JTAG capabilities say it is not a compute board', (await text('hw-caps')).includes('"compute": false'));
    check('JTAG capabilities explain level translation comes from buffers on VTref', (await text('hw-caps')).includes('level_translation'));
    await sleep(500);
    await shot('hardware', 'Hardware tab: SIMULATED devices, injected timeout then recovery by retry with backoff, telemetry, capabilities');

    check('no JavaScript errors in the console', consoleErrors.length === 0, consoleErrors.join(' | '));

    // ---- Quit ----
    await click('quit');
    await sleep(300);
    await shot('quit', 'After Quit: the page reports that the workbench stopped');
    for (let i = 0; i < 50 && !appExited; i++) await sleep(100);
    check('Quit button stops Launch.exe', appExited);
    ws.close();
  } finally {
    browser.kill();
    app.kill();
    await sleep(300);
    try { fs.rmSync(profile, { recursive: true, force: true }); } catch { /* browser still releasing files */ }
  }
  const appLog = fs.existsSync(logFile) ? fs.readFileSync(logFile, 'utf8') : '(no log file found)';
  writeWalkthrough(appLog, path.basename(browserExe).replace(/\.exe$/, ''));
  console.log(failures === 0 ? `\nUI test: ALL ${passes} CHECKS PASSED` : `\nUI test: ${failures} FAILED, ${passes} passed`);
  process.exit(failures === 0 ? 0 : 1);
}

main().catch((e) => { console.error(e); process.exit(2); });
